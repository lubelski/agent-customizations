import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdtempSync, rmSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { UiSettingsStore, loadUiSettings } from "../lib/ui/settings.ts";
import installCommands from "../lib/ui/commands.ts";

test("three independent toggles persist one setting each with one live update", async (t) => {
	const dir = mkdtempSync(join(tmpdir(), "ui-commands-"));
	t.after(() => rmSync(dir, { recursive: true, force: true }));
	const path = join(dir, "ui.json");
	const settings = new UiSettingsStore(path);
	settings.reload();
	const commands = new Map();
	const notifications = [];
	const ctx = { mode: "tui", ui: { notify: (...args) => notifications.push(args) } };
	installCommands({ registerCommand: (name, command) => commands.set(name, command) }, settings);
	assert.deepEqual([...commands.keys()], ["ui-toggle-compact-header", "ui-toggle-compact-footer", "ui-toggle-font-compat"]);
	const run = (name, args = "") => commands.get(name).handler(args, ctx);
	let updates = 0;
	settings.subscribe(() => { updates++; assert.deepEqual(settings.current, loadUiSettings(path)); });
	assert.deepEqual(settings.current, { compactHeader: false, compactFooter: false, fontCompat: false });
	await run("ui-toggle-font-compat", "bad argument");
	assert.equal(existsSync(path), false);
	await run("ui-toggle-font-compat");
	assert.deepEqual(settings.current, { compactHeader: false, compactFooter: false, fontCompat: true });
	assert.deepEqual(notifications.at(-1), ["Font compatibility on (saved).", "info"]);
	await run("ui-toggle-compact-header");
	await run("ui-toggle-compact-footer");
	assert.deepEqual(settings.current, { compactHeader: true, compactFooter: true, fontCompat: true });
	await run("ui-toggle-compact-footer");
	assert.deepEqual(settings.current, { compactHeader: true, compactFooter: false, fontCompat: true }, "toggles are orthogonal");
	assert.equal(updates, 4);
	const resumed = new UiSettingsStore(path);
	resumed.reload();
	assert.deepEqual(resumed.current, settings.current);
	const lastGood = settings.current;
	writeFileSync(path, "broken");
	await run("ui-toggle-compact-header");
	assert.equal(readFileSync(path, "utf8"), "broken");
	assert.equal(settings.current, lastGood);
	assert.equal(notifications.at(-1)[1], "error");
	rmSync(path);
	ctx.mode = "rpc";
	await run("ui-toggle-compact-header");
	assert.equal(existsSync(path), false, "noninteractive invocations do not change preferences");
});
